    private void configurarEventos() {
        // Agrupo los botones del mapa para asignarles eventos a la vez
        JButton[] estanterias = {
            jButton1, jButton2, jButton3, jButton4, jButton5,
            jButton6, jButton7, jButton8, jButton9, jButton10,
            jButton11, jButton12, jButton13, jButton14, jButton15,
            jButton16, jButton17, jButton18, jButton19, jButton20,
            jButton21, jButton22, jButton23, jButton24, jButton25
        };

        for (JButton btn : estanterias) {
            // 1. EVENTOS DE RATÓN (cursor mano y mostrar estantería al hacer clic)
            btn.addMouseListener(new MouseAdapter() {
                @Override
                public void mouseEntered(MouseEvent e) {
                    // Pone el cursor de mano sobre la estantería
                    btn.setCursor(new Cursor(Cursor.HAND_CURSOR));
                }

                @Override
                public void mouseExited(MouseEvent e) {
                    // Devuelve el cursor normal al salir
                    btn.setCursor(new Cursor(Cursor.DEFAULT_CURSOR));
                }

                @Override
                public void mouseReleased(MouseEvent e) {
                    // Enfoca la estantería y muestra su nombre al hacer clic izquierdo
                    if (e.getButton() == MouseEvent.BUTTON1) {
                        btn.requestFocusInWindow();
                        lblAyudaMapa.setText("Ubicación seleccionada: " + btn.getText());
                    }
                }
            });

            // 2. EVENTOS DE FOCO (borde azul al navegar con Tabulador)
            btn.addFocusListener(new FocusAdapter() {
                @Override
                public void focusGained(FocusEvent e) {
                    // Marca la estantería con un borde azul al recibir el foco
                    btn.setBorder(BorderFactory.createLineBorder(new Color(27, 79, 114), 2));
                }

                @Override
                public void focusLost(FocusEvent e) {
                    // Quita el borde azul al perder el foco
                    btn.setBorder(BorderFactory.createEmptyBorder(2, 6, 2, 6));
                }
            });

            // 3. EVENTOS DE TECLADO (seleccionar ubicación con Enter o Espacio)
            btn.addKeyListener(new KeyAdapter() {
                @Override
                public void keyReleased(KeyEvent e) {
                    // Muestra la estantería si se pulsa Enter o Espacio
                    if (e.getKeyCode() == KeyEvent.VK_ENTER || e.getKeyCode() == KeyEvent.VK_SPACE) {
                        lblAyudaMapa.setText("Ubicación seleccionada: " + btn.getText());
                    }
                }
            });
        }
    }

